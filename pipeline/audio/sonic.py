"""Original Kuya SoLight sonic identity options + backing bed.

Everything here is synthesised from scratch with numpy (additive/FM synthesis,
no samples, no third-party loops, no reference melodies), so SoLight Solar PH owns
the output outright. Each file gets a rights/licence metadata JSON beside it.

Usage: python3 pipeline/audio/sonic.py [out_dir]
"""
import json, sys, wave, os, datetime
import numpy as np

SR = 48000
OUT = sys.argv[1] if len(sys.argv) > 1 else 'assets/audio/sonic'
os.makedirs(OUT, exist_ok=True)

def hz(note):
    names = {'C': -9, 'C#': -8, 'D': -7, 'D#': -6, 'E': -5, 'F': -4, 'F#': -3, 'G': -2, 'G#': -1, 'A': 0, 'A#': 1, 'B': 2}
    n, o = note[:-1], int(note[-1])
    return 440.0 * 2 ** ((names[n] + (o - 4) * 12) / 12)

def env(n, a=0.004, d=0.35, s=0.0, r=0.0):
    t = np.arange(n) / SR
    e = np.minimum(1, t / a) * (s + (1 - s) * np.exp(-t / d))
    if r:
        tail = int(r * SR)
        e[-tail:] *= np.linspace(1, 0, tail)
    return e

def pluck(f, dur, bright=1.0, decay=0.45):
    n = int(dur * SR); t = np.arange(n) / SR
    y = np.zeros(n)
    for k in range(1, 9):
        y += (bright ** (k - 1)) / k * np.sin(2 * np.pi * f * k * t + k) * np.exp(-t * (1.5 + k * 1.2) / decay)
    return y * env(n, 0.003, decay * 2)

def keys(f, dur, decay=0.9):
    """Clean electric-piano-like tone (2-op FM)."""
    n = int(dur * SR); t = np.arange(n) / SR
    mod = np.sin(2 * np.pi * f * 2 * t) * 1.6 * np.exp(-t * 3)
    return np.sin(2 * np.pi * f * t + mod) * env(n, 0.004, decay)

def bell(f, dur):
    n = int(dur * SR); t = np.arange(n) / SR
    mod = np.sin(2 * np.pi * f * 3.5 * t) * 2.2 * np.exp(-t * 2.5)
    return np.sin(2 * np.pi * f * t + mod) * env(n, 0.002, 0.7)

def pad(freqs, dur, level=0.12):
    n = int(dur * SR); t = np.arange(n) / SR
    y = sum(np.sin(2 * np.pi * f * t + 0.3 * np.sin(2 * np.pi * 0.25 * t)) + 0.4 * np.sin(2 * np.pi * f * 1.003 * t) for f in freqs)
    a = np.minimum(1, t / 0.25) * np.minimum(1, (dur - t) / 0.35)
    return y / len(freqs) * a * level

def place(buf, sig, at):
    i = int(at * SR); j = min(len(buf), i + len(sig)); buf[i:j] += sig[: j - i]

def reverb(y, mix=0.18):
    out = y.copy()
    for d, g in [(0.029, 0.5), (0.037, 0.45), (0.041, 0.4), (0.053, 0.35), (0.067, 0.3), (0.079, 0.25)]:
        k = int(d * SR)
        for rep in range(1, 6):
            out[k * rep:] += y[: len(y) - k * rep] * (g ** rep) * mix
    return out

def finish(y, peak_db=-1.0):
    y = reverb(y)
    y = y / (np.max(np.abs(y)) + 1e-9) * (10 ** (peak_db / 20))
    fade = int(0.02 * SR); y[-fade:] *= np.linspace(1, 0, fade)
    return y

def write(name, y, meta):
    path = os.path.join(OUT, name + '.wav')
    st = np.stack([y, y], axis=1)
    pcm = (np.clip(st, -1, 1) * 32767).astype('<i2')
    with wave.open(path, 'wb') as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
    m = {
        'assetId': name, 'file': os.path.basename(path), 'durationSec': round(len(y) / SR, 3), 'sampleRate': SR,
        'origin': 'Original composition, synthesised procedurally in pipeline/audio/sonic.py (numpy additive/FM synthesis). No samples, loops, presets or third-party recordings used.',
        'composer': 'Generated by Claude (Anthropic) for SoLight Solar PH', 'createdAt': datetime.date.today().isoformat(),
        'license': 'Owned by SoLight Solar PH for commercial use. No third-party rights. Recommended: owner confirms originality via a quick listen against known jingles before approval.',
        'similarityCheck': 'Designed to avoid known jingles/catchphrase melodies (no reference melody used). Formal clearance (e.g. a musicologist check) is optional and not yet done.',
        'status': 'proposed', **meta,
    }
    json.dump(m, open(path.replace('.wav', '.json'), 'w'), indent=1)
    return path

# ── Option 1: "Klaro Rise" — three-note ascending, clean keys (A4 → D5 → E5, lands on the 5th) ──
def opt1(end=False):
    dur = 1.0 if not end else 1.6
    y = np.zeros(int(dur * SR))
    notes = ['A4', 'D5', 'E5'] if not end else ['E5', 'D5', 'A4']
    gaps = [0, 0.16, 0.32] if not end else [0, 0.22, 0.46]
    for n, g in zip(notes, gaps):
        place(y, keys(hz(n), dur - g, 0.55 if not end else 0.9) * (0.9 if n != notes[-1] else 1.0), g)
    place(y, pad([hz('A3'), hz('E4')] if not end else [hz('D3'), hz('A3')], dur - 0.3, 0.35), 0.3)
    return finish(y)

# ── Option 2: "SoSmart Spark" — four-note plucked-synth signature (C5 → G5 → A5 → E6) ──
def opt2(end=False):
    dur = 1.05 if not end else 1.6
    y = np.zeros(int(dur * SR))
    notes = ['C5', 'G5', 'A5', 'E6'] if not end else ['E6', 'A5', 'G5', 'C5']
    step = 0.12 if not end else 0.2
    for i, n in enumerate(notes):
        place(y, pluck(hz(n), dur - i * step, 1.0 if i < 3 else 1.2, 0.35 if not end else 0.6), i * step)
    place(y, pad([hz('C4'), hz('G4'), hz('E5')], dur - 0.35, 0.3), 0.36)
    return finish(y)

# ── Option 3: "Solar Shimmer" — rising light swell resolving to a bell chord ──
def opt3(end=False):
    dur = 1.1 if not end else 1.6
    n = int(dur * SR); t = np.arange(n) / SR
    rng = np.random.default_rng(7)
    noise = rng.standard_normal(n)
    # crude band-limited shimmer: moving-average high-pass of noise with rising envelope
    k = 24; lp = np.convolve(noise, np.ones(k) / k, mode='same'); shim = (noise - lp)
    swell_end = 0.45 if not end else 0.2
    sw = np.clip(t / swell_end, 0, 1) ** 2 * np.exp(-np.maximum(0, t - swell_end) * 12)
    y = shim * sw * 0.12
    chord = ['A5', 'C#6', 'E6', 'B6'] if not end else ['A4', 'E5', 'A5']
    for i, c in enumerate(chord):
        place(y, bell(hz(c), dur - swell_end) * (0.8 - i * 0.1), swell_end + i * 0.025)
    place(y, pad([hz('A3'), hz('E4'), hz('C#5')], dur - swell_end, 0.4), swell_end)
    return finish(y)

# ── Backing bed (A major, ~100 bpm). Related to option 1/3 tonality. Mixed low under narration. ──
A_PROG = [['A3', 'C#4', 'E4'], ['F#3', 'A3', 'C#4'], ['D3', 'F#3', 'A3'], ['E3', 'G#3', 'B3']]
C_PROG = [['C4', 'E4', 'G4'], ['A3', 'C4', 'E4'], ['F3', 'A3', 'C4'], ['G3', 'B3', 'D4']]  # matches option 2 (SoSmart Spark)

def bed(seconds=64.0, prog=A_PROG):
    bpm = 100; beat = 60 / bpm
    y = np.zeros(int(seconds * SR))
    bar = beat * 4; t = 0.0; i = 0
    while t < seconds:
        ch = prog[i % 4]
        place(y, pad([hz(n) for n in ch], min(bar + 0.3, seconds - t), 0.55), t)
        place(y, pad([hz(ch[0][:-1] + str(int(ch[0][-1]) - 1))], min(bar, seconds - t), 0.35), t)
        for b in range(8):  # soft eighth-note pluck arpeggio
            nt = ch[b % 3]; nt = nt[:-1] + str(int(nt[-1]) + 1)
            if t + b * beat / 2 < seconds - 0.4:
                place(y, pluck(hz(nt), 0.5, 0.7, 0.25) * (0.22 if b % 2 == 0 else 0.15), t + b * beat / 2)
        t += bar; i += 1
    y = finish(y, -3.0)
    fade = int(1.5 * SR); y[:int(0.4 * SR)] *= np.linspace(0, 1, int(0.4 * SR)); y[-fade:] *= np.linspace(1, 0, fade)
    return y

if __name__ == '__main__':
    specs = [
        ('sonic-1-klaro-rise', opt1, 'Three-note ascending sonic logo on clean FM keys: A4, D5, E5 over a soft A pad.'),
        ('sonic-2-sosmart-spark', opt2, 'Four-note plucked-synth signature: C5, G5, A5, E6 with an airy C pad.'),
        ('sonic-3-solar-shimmer', opt3, 'Solar-energy cue: rising shimmer swell resolving into an A-major add9 bell chord.'),
    ]
    for name, fn, desc in specs:
        write(name, fn(False), {'role': 'opening sting', 'description': desc})
        write(name + '-end', fn(True), {'role': 'softer resolved closing variation', 'description': desc + ' Closing variant: slower, descending resolution to the tonic.'})
    write('bed-a-major-100bpm', bed(), {'role': 'optional background music bed', 'description': 'Quiet A-major pad + pluck arpeggio, 100 bpm, 64 s. Key-related to sonic options 1 and 3. Always mixed under narration with ducking; music-free versions are rendered for comparison.'})
    write('bed-c-major-100bpm', bed(prog=C_PROG), {'role': 'background music bed for the approved sonic logo (SoSmart Spark)', 'description': 'Quiet C-major pad + pluck arpeggio (C, Am, F, G), 100 bpm, 64 s. Same key as sonic option 2. Always mixed under narration with ducking.'})
    print('sonic assets written to', OUT)
